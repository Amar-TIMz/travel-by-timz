function googleLookup(query) {
  return 'https://www.google.com/search?' + new URLSearchParams({q:query,hl:'ms'});
}

function appendPartner(container, label, href, detail) {
  const link = document.createElement('a');
  link.textContent = label;
  link.className = 'partner-link';
  link.href = href;
  link.target = '_blank';
  link.rel = 'noopener noreferrer';
  link.title = detail;
  link.setAttribute('aria-label', detail);
  container.append(link);
  return link;
}

// Configure window.TIMZ_WEATHER_ENDPOINT for optional inline observations.
// Endpoint takes ?place=... and returns Google's currentConditions.lookup
// payload plus countryCode and placeName. Keep the API key on that server.
async function readGoogleWeather(container, placeName) {
  const endpoint = window.TIMZ_WEATHER_ENDPOINT;
  if (!endpoint) return;
  try {
    const url = new URL(endpoint, location.href);
    if (url.protocol !== 'https:') return;
    url.searchParams.set('place', placeName);
    const response = await fetch(url, {credentials:'omit', signal:AbortSignal.timeout(8000)});
    if (!response.ok) return;
    const weather = await response.json();
    const observed = new Date(weather.currentTime);
    const degrees = weather.temperature?.degrees;
    const country = String(weather.countryCode || '').toUpperCase();
    if (!country || country === 'ID' || !Number.isFinite(degrees) ||
        weather.temperature.unit !== 'CELSIUS' || !Number.isFinite(+observed) ||
        Date.now() - observed.getTime() > 3*3600000) return;
    const label = document.createElement('p');
    const time = new Intl.DateTimeFormat('ms-MY', {hour:'2-digit',minute:'2-digit',timeZone:weather.timeZone?.id,timeZoneName:'short'}).format(observed);
    label.textContent = [weather.placeName || placeName, Math.round(degrees)+' °C', weather.weatherCondition?.description?.text, time, 'Google Maps'].filter(Boolean).join(' · ');
    if (country === 'JP' || country === 'KR') {
      const korean = country === 'KR';
      label.append(document.createTextNode(korean ? ' · 날씨 정보 제공: ' : ' · 気象データ提供：'));
      appendPartner(label, korean ? '웨더뉴스' : '株式会社ウェザーニューズ', korean ? 'https://kr.weathernews.com/' : 'https://jp.weathernews.com/', 'Weathernews');
    }
    container.append(label);
  } catch { /* The Google Weather link remains available on API and network errors. */ }
}

function renderPartners(container, place, options = {}) {
  const name = typeof place === 'string' ? place : place.name;
  const key = partnerKey(name.trim());
  const destination = partnerAliases[key] || knownPlaceNames.get(key) || name;
  const url = travelokaDestinations[destination];
  const optionsObject = typeof options === 'number' ? {start: options} : options;
  const code = (typeof place === 'object' && place.airport) || flightGateways[destination] ||
    optionsObject.airport || TIMZ_GATEWAYS_BY_PAGE[optionsObject.start];
  container.replaceChildren();
  appendPartner(container, 'Booking.com', 'https://www.booking.com/searchresults.html?' + new URLSearchParams({ss:name,selected_currency:'MYR'}), 'Cari penginapan sekitar ' + name + ' di Booking.com');
  const plannerUrl = 'https://www.traveloka.com/en-my/travel-planner?' + new URLSearchParams({v:'1',destination:name});
  appendPartner(container, url ? 'Traveloka' : 'Perancang Traveloka', url || plannerUrl, (url ? 'Terokai ' : 'Rancang lawatan ke ') + name + ' di Traveloka');
  appendPartner(container, 'Trip.com', 'https://my.trip.com/global-search/searchlist/search/?' + new URLSearchParams({keyword:name}), 'Cari ' + name + ' di Trip.com');
  if (code && /^[A-Z]{3}$/.test(code) && code !== 'KUL') {
    appendPartner(container, 'Skyscanner · KUL → ' + code, 'https://www.skyscanner.com.my/transport/flights/kul/' + code.toLowerCase() + '/', 'Cari penerbangan dari Kuala Lumpur ke ' + code + ' di Skyscanner');
  } else {
    appendPartner(container, 'Skyscanner · carian Google', googleLookup('site:skyscanner.com.my flights from Kuala Lumpur to ' + name), 'Cari penerbangan Skyscanner untuk ' + name + ' melalui Google');
  }
  appendPartner(container, 'Cuaca di Google', googleLookup('cuaca sekarang ' + name), 'Semak cuaca terkini untuk ' + name + ' di Google');
  const observation = document.createElement('div');
  container.append(observation);
  readGoogleWeather(observation, name);
}
